import { describe, expect, it } from 'vitest';

import { typograph } from './typography';

const NBSP = ' ';

describe('typograph', () => {
  it('заменяет прямые кавычки на «ёлочки», а вложенные — на „лапки“', () => {
    expect(typograph('Склад "Южный-2" компании "Агро "Север""')).toBe(
      'Склад «Южный-2» компании «Агро „Север“»',
    );
  });

  it('ставит длинное тире с неразрывным пробелом перед ним', () => {
    expect(typograph('Паводок - склад под угрозой')).toBe(`Паводок${NBSP}— склад под угрозой`);
    expect(typograph('Паводок — склад')).toBe(`Паводок${NBSP}— склад`);
  });

  it('не трогает дефис внутри слова', () => {
    expect(typograph('Южный-2 и Северо-Запад')).toBe('Южный-2 и Северо-Запад');
  });

  it('связывает «₽», «№» и единицы измерения с числом', () => {
    expect(typograph('Платёж 1 250 000 ₽ по договору №42, файл до 10 МБ, груз 40 т.')).toBe(
      `Платёж 1${NBSP}250${NBSP}000${NBSP}₽ по договору №${NBSP}42, файл до 10${NBSP}МБ, груз 40${NBSP}т.`,
    );
  });

  it('не связывает число со словом, которое только начинается как единица', () => {
    expect(typograph('5 магазинов и 3 тонны')).toBe('5 магазинов и 3 тонны');
  });
});
