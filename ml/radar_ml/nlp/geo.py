def norm_country(raw: str) -> str:
    """'ЮЖНАЯ КОРЕЯ' -> 'Южная Корея', 'ОАЭ' -> 'ОАЭ', 'США' -> 'США'."""
    raw = raw.strip()
    if not raw:
        return raw
    if len(raw) <= 4 and raw.isupper():
        return raw
    parts = re.split(r"([\s\-])", raw.lower())
    out = []
    for i, p in enumerate(parts):
        if p in {"и", "д'ивуар"} and i > 0:
            out.append(p)
        else:
            out.append(p[:1].upper() + p[1:])
    return "".join(out)


def region_display(dataset_region: str | None) -> str | None:
    if not dataset_region:
        return None
    entry = REGIONS.get(dataset_region)
    return entry[0] if entry else dataset_region


def norm_city(raw: str | None) -> str | None:
    if not raw or not isinstance(raw, str):
        return None
    c = re.sub(r"^\s*(г\.|город)\s*", "", raw).strip()
    # «Ростов-На-Дону» -> «Ростов-на-Дону», «Комсомольск-На-Амуре» -> «Комсомольск-на-Амуре»
    c = re.sub(r"-На-", "-на-", c)
    return c or None


@lru_cache
def _region_regex() -> list[tuple[str, re.Pattern[str]]]:
    out = []
    for key, (_display, pats, _fd) in REGIONS.items():
        out.append((key, re.compile("|".join(f"(?:{p})" for p in pats))))
    return out


@lru_cache
def _country_regex() -> list[tuple[str, re.Pattern[str]]]:
    return [(k, re.compile("|".join(f"(?:{p})" for p in v))) for k, v in COUNTRIES.items()]


@lru_cache
def _currency_regex() -> list[tuple[str, re.Pattern[str]]]:
    return [(k, re.compile("|".join(f"(?:{p})" for p in v))) for k, v in CURRENCY_PATTERNS.items()]


def find_regions(text_lower: str) -> list[str]:
    """Регионы (ключи датасета), упомянутые в тексте."""
    return [k for k, rx in _region_regex() if rx.search(text_lower)]


def find_countries(text_lower: str) -> list[str]:
    return [k for k, rx in _country_regex() if rx.search(text_lower)]


def find_currencies(text_lower: str) -> list[str]:
    return [k for k, rx in _currency_regex() if rx.search(text_lower)]
